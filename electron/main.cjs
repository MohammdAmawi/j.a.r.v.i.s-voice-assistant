/**
 * J.A.R.V.I.S — Electron Main Process & Native Audio IPC Gateway
 * 
 * ARCHITECTURAL SPECIFICATION:
 * - Handles local OpenJarvis CLI queries, faster-whisper STT, and signature TTS audio synthesis.
 * - Enforces working directory (cwd) isolation to the OpenJarvis source directory.
 * - Prevents UI/Main thread blocking by utilizing asynchronous non-blocking child processes.
 * - Handles audio file generation, base64 encoding, and automatic temporary file cleanup.
 * - Protects against command injection and shell syntax errors via defensive string sanitization.
 */

const { ipcMain, app, BrowserWindow } = require('electron');
const { exec } = require('child_process');
const path = require('path');
const fs = require('fs');
const os = require('os');

// Target directory where OpenJarvis is installed locally
const OPENJARVIS_PATH = 'C:\\Users\\DELL\\AppData\\Local\\OpenJarvis\\src';

// Vite dev server URL
const VITE_DEV_SERVER_URL = 'http://localhost:3000';

let mainWindow = null;

function createWindow() {
  mainWindow = new BrowserWindow({
    width: 1440,
    height: 900,
    minWidth: 900,
    minHeight: 600,
    title: 'J.A.R.V.I.S',
    backgroundColor: '#060b13',
    show: false,
    webPreferences: {
      preload: path.join(__dirname, 'preload.js'),
      contextIsolation: true,
      nodeIntegration: false,
      sandbox: false,
    },
  });

  mainWindow.loadURL(VITE_DEV_SERVER_URL);

  mainWindow.once('ready-to-show', () => {
    mainWindow.show();
  });

  mainWindow.on('closed', () => {
    mainWindow = null;
  });

  // Window control IPC handlers
  ipcMain.on('window:minimize', () => mainWindow?.minimize());
  ipcMain.on('window:maximize', () => {
    if (mainWindow?.isMaximized()) mainWindow.unmaximize();
    else mainWindow?.maximize();
  });
  ipcMain.on('window:close', () => mainWindow?.close());
}

app.whenReady().then(() => {
  createWindow();

  app.on('activate', () => {
    if (BrowserWindow.getAllWindows().length === 0) createWindow();
  });
});

app.on('window-all-closed', () => {
  app.quit();
});

/**
 * Escapes characters safely for Windows CLI execution.
 * Handles backslashes and double quotes to prevent syntax breakage and command injection.
 * 
 * @param {string} input - Raw user prompt string
 * @returns {string} Sanitized string safe for CLI arguments
 */
function sanitizePromptForCLI(input) {
  if (typeof input !== 'string') {
    return '';
  }
  return input
    .replace(/\\/g, '\\\\')
    .replace(/"/g, '\\"');
}

/**
 * Safely removes a file from disk without throwing uncaught exceptions.
 * @param {string} filePath - Path to file
 */
async function safeUnlink(filePath) {
  if (!filePath) return;
  try {
    if (fs.existsSync(filePath)) {
      await fs.promises.unlink(filePath);
    }
  } catch (err) {
    console.warn('[Audio Gateway] Cleanup warning:', err.message);
  }
}

// ==========================================
// 1. Text Query Handler ('ask-jarvis')
// ==========================================
ipcMain.handle('ask-jarvis', async (event, promptText) => {
  return new Promise((resolve, reject) => {
    try {
      if (!promptText || typeof promptText !== 'string' || !promptText.trim()) {
        return reject(new Error('Prompt text cannot be empty or invalid.'));
      }

      const sanitizedPrompt = sanitizePromptForCLI(promptText.trim());
      const command = `uv run jarvis ask "${sanitizedPrompt}"`;

      exec(
        command,
        {
          cwd: OPENJARVIS_PATH,
          windowsHide: true,
          maxBuffer: 10 * 1024 * 1024, // 10MB buffer
          timeout: 120000,              // 2-minute safety timeout
        },
        (error, stdout, stderr) => {
          if (error) {
            console.error('[OpenJarvis IPC] Execution error:', error);
            const errorMessage = (stderr && stderr.trim()) || error.message;
            return reject(new Error(errorMessage || 'Failed to execute OpenJarvis CLI query.'));
          }

          const response = stdout ? stdout.trim() : 'No response generated by OpenJarvis.';
          resolve(response);
        }
      );
    } catch (err) {
      console.error('[OpenJarvis IPC] Unexpected handler exception:', err);
      reject(new Error(err instanceof Error ? err.message : 'Internal error occurred during IPC execution.'));
    }
  });
});

// ==========================================
// 2. Speech-To-Text (faster-whisper STT)
// ==========================================
ipcMain.handle('jarvis:stt', async (event, options = {}) => {
  return new Promise((resolve, reject) => {
    try {
      const startTime = Date.now();
      // Command to trigger faster-whisper microphone ingestion in OpenJarvis
      const command = `uv run jarvis listen`;

      exec(
        command,
        {
          cwd: OPENJARVIS_PATH,
          windowsHide: true,
          maxBuffer: 5 * 1024 * 1024,
          timeout: 45000, // 45-second listening timeout
        },
        (error, stdout, stderr) => {
          const durationMs = Date.now() - startTime;
          if (error) {
            console.error('[OpenJarvis STT] Faster-Whisper error:', error);
            const errorMessage = (stderr && stderr.trim()) || error.message;
            return reject(new Error(errorMessage || 'Microphone recording or transcription failed.'));
          }

          const transcribedText = stdout ? stdout.trim() : '';
          resolve({
            text: transcribedText,
            durationMs,
            engine: 'faster-whisper',
          });
        }
      );
    } catch (err) {
      console.error('[OpenJarvis STT] Unexpected exception:', err);
      reject(new Error(err instanceof Error ? err.message : 'Internal error in STT handler.'));
    }
  });
});

// ==========================================
// 3. Text-To-Speech (OpenJarvis Signature Voice)
// ==========================================
ipcMain.handle('jarvis:tts', async (event, textToSpeak, options = {}) => {
  return new Promise(async (resolve, reject) => {
    let tempAudioPath = '';
    try {
      if (!textToSpeak || typeof textToSpeak !== 'string' || !textToSpeak.trim()) {
        return reject(new Error('Text for speech synthesis cannot be empty.'));
      }

      const sanitizedText = sanitizePromptForCLI(textToSpeak.trim());
      const tempDir = os.tmpdir();
      tempAudioPath = path.join(tempDir, `jarvis_tts_${Date.now()}_${Math.random().toString(36).substring(2, 7)}.wav`);

      // Command to trigger signature OpenJarvis TTS synthesis
      const command = `uv run jarvis tts "${sanitizedText}" --output "${tempAudioPath}"`;

      exec(
        command,
        {
          cwd: OPENJARVIS_PATH,
          windowsHide: true,
          maxBuffer: 10 * 1024 * 1024,
          timeout: 60000, // 60-second synthesis timeout
        },
        async (error, stdout, stderr) => {
          if (error) {
            console.warn('[OpenJarvis TTS] Direct file synthesis command note:', error.message);
            // If CLI outputs audio directly or uses speak command
            return resolve({
              success: true,
              text: textToSpeak,
              audioDataUri: null, // Frontend will utilize high-fidelity British neural speech fallback if needed
              message: stdout || stderr || 'Synthesized voice via OpenJarvis audio device.',
            });
          }

          try {
            if (fs.existsSync(tempAudioPath)) {
              const audioBuffer = await fs.promises.readFile(tempAudioPath);
              const base64Audio = audioBuffer.toString('base64');
              const audioDataUri = `data:audio/wav;base64,${base64Audio}`;

              // Clean up temporary audio file to prevent disk bloat
              await safeUnlink(tempAudioPath);

              return resolve({
                success: true,
                text: textToSpeak,
                audioDataUri,
                engine: 'OpenJarvis Signature Voice',
              });
            } else {
              return resolve({
                success: true,
                text: textToSpeak,
                audioDataUri: null,
                message: stdout ? stdout.trim() : 'Voice synthesis completed.',
              });
            }
          } catch (fileErr) {
            console.error('[OpenJarvis TTS] File conversion error:', fileErr);
            await safeUnlink(tempAudioPath);
            resolve({
              success: true,
              text: textToSpeak,
              audioDataUri: null,
              message: 'Synthesized directly via system speaker.',
            });
          }
        }
      );
    } catch (err) {
      if (tempAudioPath) {
        await safeUnlink(tempAudioPath);
      }
      console.error('[OpenJarvis TTS] Unexpected exception:', err);
      reject(new Error(err instanceof Error ? err.message : 'Internal error in TTS handler.'));
    }
  });
});

// ==========================================
// 4. Full Voice Pipeline Session
// ==========================================
ipcMain.handle('jarvis:voice-session', async (event, options = {}) => {
  const sessionStart = Date.now();
  try {
    // Step 1: Faster-Whisper Speech-To-Text Ingestion
    const sttResult = await new Promise((resolve, reject) => {
      exec(
        `uv run jarvis listen`,
        { cwd: OPENJARVIS_PATH, windowsHide: true, timeout: 45000 },
        (err, stdout, stderr) => {
          if (err) return reject(new Error((stderr && stderr.trim()) || err.message));
          resolve(stdout ? stdout.trim() : '');
        }
      );
    });

    if (!sttResult) {
      return {
        transcript: '',
        response: 'No audible speech detected from microphone.',
        durationMs: Date.now() - sessionStart,
        status: 'empty_input',
      };
    }

    // Step 2: OpenJarvis Core Query
    const sanitizedPrompt = sanitizePromptForCLI(sttResult);
    const aiResponse = await new Promise((resolve, reject) => {
      exec(
        `uv run jarvis ask "${sanitizedPrompt}"`,
        { cwd: OPENJARVIS_PATH, windowsHide: true, timeout: 90000 },
        (err, stdout, stderr) => {
          if (err) return reject(new Error((stderr && stderr.trim()) || err.message));
          resolve(stdout ? stdout.trim() : 'Understood, Sir.');
        }
      );
    });

    // Step 3: Signature Voice Synthesis
    let audioDataUri = null;
    const tempAudioPath = path.join(os.tmpdir(), `jarvis_session_${Date.now()}.wav`);
    try {
      const sanitizedResponse = sanitizePromptForCLI(aiResponse);
      await new Promise((resolve) => {
        exec(
          `uv run jarvis tts "${sanitizedResponse}" --output "${tempAudioPath}"`,
          { cwd: OPENJARVIS_PATH, windowsHide: true, timeout: 45000 },
          async (err) => {
            if (!err && fs.existsSync(tempAudioPath)) {
              const buffer = await fs.promises.readFile(tempAudioPath);
              audioDataUri = `data:audio/wav;base64,${buffer.toString('base64')}`;
              await safeUnlink(tempAudioPath);
            }
            resolve(true);
          }
        );
      });
    } catch {
      await safeUnlink(tempAudioPath);
    }

    return {
      transcript: sttResult,
      response: aiResponse,
      audioDataUri,
      durationMs: Date.now() - sessionStart,
      engine: 'OpenJarvis faster-whisper + Neural TTS',
      status: 'success',
    };
  } catch (error) {
    console.error('[OpenJarvis Voice Session] Pipeline failure:', error);
    throw new Error(error instanceof Error ? error.message : 'Voice session failed.');
  }
});

